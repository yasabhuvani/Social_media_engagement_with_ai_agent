import React from 'react';
import { Database, Sparkles, Lightbulb, RefreshCw, CheckCircle2 } from 'lucide-react';

export type TagType = 'historical' | 'insight' | 'recommendation' | 'feedback' | 'verified';

interface BadgeTagProps {
  type: TagType;
  label?: string;
  size?: 'sm' | 'md';
}

export const BadgeTag: React.FC<BadgeTagProps> = ({ type, label, size = 'sm' }) => {
  const isSm = size === 'sm';
  const sizeClasses = isSm ? 'text-[11px] px-2 py-0.5 gap-1.5' : 'text-xs px-2.5 py-1 gap-2';

  if (type === 'historical') {
    return (
      <span
        className={`inline-flex items-center font-medium rounded-full bg-blue-950/80 text-blue-300 border border-blue-500/30 shadow-xs tracking-wide uppercase ${sizeClasses}`}
        title="Verified statistical data from historical social media posts"
      >
        <Database className={isSm ? 'w-3 h-3 text-blue-400' : 'w-3.5 h-3.5 text-blue-400'} />
        <span>{label || 'Historical Data'}</span>
      </span>
    );
  }

  if (type === 'insight') {
    return (
      <span
        className={`inline-flex items-center font-medium rounded-full bg-purple-950/80 text-purple-300 border border-purple-500/30 shadow-xs tracking-wide uppercase ${sizeClasses}`}
        title="Pattern or rule synthesized from audience reactions and metrics"
      >
        <Sparkles className={isSm ? 'w-3 h-3 text-purple-400' : 'w-3.5 h-3.5 text-purple-400'} />
        <span>{label || 'AI Insight'}</span>
      </span>
    );
  }

  if (type === 'recommendation') {
    return (
      <span
        className={`inline-flex items-center font-medium rounded-full bg-emerald-950/80 text-emerald-300 border border-emerald-500/30 shadow-xs tracking-wide uppercase ${sizeClasses}`}
        title="Data-grounded actionable proposal generated by the agent"
      >
        <Lightbulb className={isSm ? 'w-3 h-3 text-emerald-400' : 'w-3.5 h-3.5 text-emerald-400'} />
        <span>{label || 'Recommendation'}</span>
      </span>
    );
  }

  if (type === 'feedback') {
    return (
      <span
        className={`inline-flex items-center font-medium rounded-full bg-amber-950/80 text-amber-300 border border-amber-500/30 shadow-xs tracking-wide uppercase ${sizeClasses}`}
        title="Learned from real post performance feedback loop"
      >
        <RefreshCw className={isSm ? 'w-3 h-3 text-amber-400' : 'w-3.5 h-3.5 text-amber-400'} />
        <span>{label || 'Feedback Learned'}</span>
      </span>
    );
  }

  return (
    <span
      className={`inline-flex items-center font-medium rounded-full bg-slate-800 text-slate-300 border border-slate-700 ${sizeClasses}`}
    >
      <CheckCircle2 className={isSm ? 'w-3 h-3 text-slate-400' : 'w-3.5 h-3.5 text-slate-400'} />
      <span>{label || 'Verified'}</span>
    </span>
  );
};
